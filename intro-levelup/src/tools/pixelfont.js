G[':'] = '././#/././#/.';
// normalise to row arrays
const glyphs = {};
for (const [ch, s] of Object.entries(G)) {
  const rows = s.split('/'), w = Math.max(...rows.map(r => r.length));
  glyphs[ch] = rows.map(r => r.padEnd(w, '.'));
}
fs.writeFileSync(A('pixelfont.json'), JSON.stringify(glyphs));

// webfont: 100 units per pixel, 1 px of tracking after every glyph
let opentype = null;
try { opentype = require('opentype.js'); } catch (e) { console.log('opentype.js not found: wrote pixelfont.json only'); }
if (opentype) {
  const U = 100, glyphList = [new opentype.Glyph({ name: '.notdef', unicode: 0, advanceWidth: 600, path: new opentype.Path() })];
  for (const [ch, rows] of Object.entries(glyphs)) {
    const p = new opentype.Path();
    rows.forEach((row, r) => {
      const y1 = (7 - r) * U, y0 = y1 - U;   // row r spans [y0, y1] above the baseline
      for (let x = 0; x < row.length;) {
        if (row[x] !== '#') { x++; continue; }
        let e = x; while (e < row.length && row[e] === '#') e++;
        p.moveTo(x * U, y0); p.lineTo(e * U, y0); p.lineTo(e * U, y1); p.lineTo(x * U, y1); p.close();
        x = e;
      }
    });
    glyphList.push(new opentype.Glyph({ name: 'u' + ch.codePointAt(0).toString(16), unicode: ch.codePointAt(0), advanceWidth: (rows[0].length + 1) * U, path: p }));
  }
  const font = new opentype.Font({ familyName: 'GZ2H Pixel', styleName: 'Regular', unitsPerEm: 1000, ascender: 800, descender: -200, glyphs: glyphList });
  fs.writeFileSync(A('GZ2HPixel.otf'), Buffer.from(font.toArrayBuffer()));
}
